package CursoTodoCode;

public class TiposDatos {
    public int num =12; //entero
    public float flota = 12.1234f;//fotante
    public double dobleF = 1234.123;//doblemetne fotante
    public char caracter = 'f';//caracter
    public boolean bol = true;//boleano
    public String cadena = "hello";//cadena de caracteres
    public long longi = 134234234; // largo


    //Enteros
    public byte miByte = 34;//rango: -128 a 127. 8 bits
    public short miShort = 12341;//rango: -32,768 a 32,767, 16 bit
    public int miInte = 1234;//32 bits → el más usado para enteros
    public long miLong = 123455L;//64 bits → para números muy grande

    //MUNEROS DECIMALES
    public float miFloat = 1234.1234f;//menor precisión
    public double miDouble = 1234.123412341;//más precisión (más usado)

    //CARACTER
    public char miChart = 'f'; //16 bits → almacena un solo carácter (ej: 'A', '3', '@')

    //BOLEAN
    public boolean miBolean = true;//solo puede tener dos valores: true o false



}
